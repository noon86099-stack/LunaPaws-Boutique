export function translateText(text: string, language: StoreLanguage): string {
  if (language === "en") return text;
  const trimmed = text.trim();
  const direct = arabicCopy[trimmed];
  if (direct) return text.replace(trimmed, direct);
  const patterns: [RegExp, (match: RegExpMatchArray) => string][] = [
    [/^(.+) added to your bag$/, m => `تمت إضافة ${translateText(m[1]!, "ar")} إلى سلتك`],
    [/^(\d+) thoughtfully picked pieces$/, m => `${m[1]} منتجات مختارة بعناية`],
    [/^View favorites, (\d+) items$/, m => `عرض المفضّلة، ${m[1]} منتجات`],
    [/^Open bag, (\d+) items$/, m => `فتح السلة، ${m[1]} منتجات`],
    [/^Your bag \((\d+)\)$/, m => `سلتك (${m[1]})`],
    [/^Saved pieces \((\d+)\)$/, m => `المفضّلة (${m[1]})`],
    [/^Shop (.+)$/, m => `تسوّق ${translateText(m[1]!, "ar")}`],
    [/^View (.+)$/, m => `عرض ${translateText(m[1]!, "ar")}`],
    [/^Add (.+) to favorites$/, m => `إضافة ${translateText(m[1]!, "ar")} إلى المفضّلة`],
    [/^Remove (.+) from favorites$/, m => `إزالة ${translateText(m[1]!, "ar")} من المفضّلة`],
    [/^Add (.+) to bag$/, m => `إضافة ${translateText(m[1]!, "ar")} إلى السلة`],
    [/^Decrease (.+) quantity$/, m => `تقليل كمية ${translateText(m[1]!, "ar")}`],
    [/^Increase (.+) quantity$/, m => `زيادة كمية ${translateText(m[1]!, "ar")}`],
    [/^Remove (.+)$/, m => `إزالة ${translateText(m[1]!, "ar")}`],
    [/^(.+) for cats$/, m => `${translateText(m[1]!, "ar")} للقطط`],
    [/^KWD ([\d.]+)$/, m => `${m[1]} د.ك`],
    [/^(\d*) happy homes\)$/, m => `${m[1]} بيوت سعيدة)`],
  ];
  if (trimmed === "happy homes)") return text.replace(trimmed, "بيوت سعيدة)");
  for (const [pattern, translate] of patterns) {
    const match = trimmed.match(pattern);
    if (match) return text.replace(trimmed, translate(match));
  }
  return text;
}

/** Translate only display copy. Inputs, handlers, IDs, URLs and state are untouched. */
export function localizeContent(node: ReactNode, language: StoreLanguage): ReactNode {
  if (language === "en") return node;
  if (typeof node === "string") return translateText(node, language);
  if (Array.isArray(node)) return Children.map(node, child => localizeContent(child, language));
  if (!isValidElement(node) || node.type === "style" || node.type === "script") return node;
  const element = node as ReactElement<Record<string, unknown>>;
  const props: Record<string, unknown> = {};
  for (const attribute of ["aria-label", "placeholder", "alt", "title"]) {
    if (typeof element.props[attribute] === "string") {
      props[attribute] = translateText(element.props[attribute] as string, language);
    }
  }
  if ("children" in element.props) {
    props.children = localizeContent(element.props.children as ReactNode, language);
  }
  return cloneElement(element, props);
}
